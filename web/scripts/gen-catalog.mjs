// NOTE: Generates src/lib/registry/catalog.generated.ts - the light catalog
// (slug/title/description/category/firstStepId) that keeps the full registry
// off non-tool routes (EIT-132). TS loads like in gen-og.mjs (Node 24).
import { mkdirSync, writeFileSync, readdirSync, readFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { join } from "node:path";
import prettier from "prettier";

const LIB = fileURLToPath(new URL("../src/lib/", import.meta.url));

// NOTE: File order comes from the PAGES spread in registry/index.ts, so the
// catalog keeps the PAGES order that featured/search tie-breaks rely on.
function orderedPageFiles() {
	const dir = join(LIB, "registry", "pages");
	const index = readFileSync(join(LIB, "registry", "index.ts"), "utf8");
	const block = /export const PAGES = \[([\s\S]*?)\];/.exec(index);
	const files = [...block[1].matchAll(/\.\.\.(\w+)Pages/g)].map(
		(match) => `${match[1]}.ts`,
	);
	if (files.length === 0) {
		throw new Error("PAGES spread not found in registry/index.ts");
	}
	const onDisk = readdirSync(dir).filter(
		(file) => file.endsWith(".ts") && !file.endsWith(".test.ts"),
	);
	const unlisted = onDisk.filter((file) => !files.includes(file));
	if (unlisted.length > 0) {
		throw new Error(`pages not imported by registry/index.ts: ${unlisted}`);
	}
	return files;
}

async function loadPages() {
	const dir = join(LIB, "registry", "pages");
	const pages = [];
	for (const file of orderedPageFiles()) {
		const mod = await import(pathToFileURL(join(dir, file)).href);
		for (const value of Object.values(mod)) {
			if (Array.isArray(value)) pages.push(...value);
		}
	}
	return pages;
}

const pages = await loadPages();
for (const page of pages) {
	if (!page.steps?.[0]?.id) {
		throw new Error(`page without a first step: ${page.slug}`);
	}
}

const rows = pages
	.map(
		(page) =>
			`\t{ slug: ${JSON.stringify(page.slug)}, title: ${JSON.stringify(page.title)}, description: ${JSON.stringify(page.description)}, category: ${JSON.stringify(page.category)}, firstStepId: ${JSON.stringify(page.steps[0].id)} },`,
	)
	.join("\n");

const body = `// NOTE: Generated by scripts/gen-catalog.mjs - regenerate, do not edit.
import type { CategoryId } from "../categories";

export type PageMeta = {
	slug: string;
	title: string;
	description: string;
	category: CategoryId;
};

export type CatalogEntry = PageMeta & { firstStepId: string };

export const CATALOG: CatalogEntry[] = [
${rows}
];
`;

const outPath = join(LIB, "registry", "catalog.generated.ts");
const config = await prettier.resolveConfig(outPath);
const formatted = await prettier.format(body, { ...config, filepath: outPath });
mkdirSync(join(LIB, "registry"), { recursive: true });
writeFileSync(outPath, formatted);
console.log(`catalog.generated.ts written: ${pages.length} pages`);
