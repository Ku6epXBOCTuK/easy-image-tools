// NOTE: Copies the used IBM Plex woff2 faces to static/fonts (stable names for
// app.html preload) and generates src/fonts.generated.css: real @font-face
// rules plus metric-matched fallback faces against font-swap shift (EIT-132).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const require = createRequire(import.meta.url);
const fontkit = require("fontkit");

const WEB = fileURLToPath(new URL("..", import.meta.url));

const FAMILIES = [
	{
		pkg: "ibm-plex-sans",
		family: "IBM Plex Sans",
		weights: [400, 500, 600, 700],
	},
	{ pkg: "ibm-plex-mono", family: "IBM Plex Mono", weights: [400, 500] },
];
const SUBSETS = ["latin", "latin-ext", "cyrillic", "cyrillic-ext"];

// NOTE: Arial metrics measured once via fontkit from Windows Arial (v7);
// fixed constants keep the generator deterministic on every machine.
const FALLBACK = {
	upem: 2048,
	ascent: 1854,
	descent: 434,
	lineGap: 67,
	avgWidth: 0.5791,
};
const SAMPLE = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";

function parseFaces(pkg, weight) {
	const css = readFileSync(
		join(WEB, "node_modules", "@fontsource", pkg, `${weight}.css`),
		"utf8",
	);
	const faces = [];
	const re = /@font-face\s*\{([^}]+)\}/g;
	for (const [, body] of css.matchAll(re)) {
		const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
		const file = /url\(\.\/files\/([a-z0-9-]+-normal\.woff2)\)/.exec(body)?.[1];
		if (!range || !file) continue;
		const subset = file
			.replace(/\.woff2$/, "")
			.split("-")
			.slice(3, -2)
			.join("-");
		if (!SUBSETS.includes(subset)) continue;
		faces.push({ subset, range, file });
	}
	if (faces.length === 0) throw new Error(`${pkg}/${weight}: no subset faces`);
	return faces;
}

function measure(file) {
	const font = fontkit.openSync(
		join(
			WEB,
			"node_modules",
			"@fontsource",
			file.family.pkg,
			"files",
			file.name,
		),
	);
	let total = 0;
	for (const ch of SAMPLE) {
		total += font.glyphForCodePoint(ch.codePointAt(0)).advanceWidth;
	}
	return {
		upem: font.unitsPerEm,
		ascent: font.hhea.ascent,
		descent: -font.hhea.descent,
		lineGap: font.hhea.lineGap,
		avgWidth: total / SAMPLE.length / font.unitsPerEm,
	};
}

// NOTE: Formulas from the fontaine/next-font approach: the fallback face gets
// Plex line metrics (divided by size-adjust, which rescales the em) so the
// swap between fallback and real font moves no layout.
function fallbackFace(main) {
	const sizeAdjust = main.avgWidth / FALLBACK.avgWidth;
	const pct = (value) =>
		`${((value / (main.upem * sizeAdjust)) * 100).toFixed(2)}%`;
	return {
		sizeAdjust: `${(sizeAdjust * 100).toFixed(2)}%`,
		ascent: pct(main.ascent),
		descent: pct(main.descent),
		lineGap: pct(main.lineGap),
	};
}

mkdirSync(join(WEB, "static", "fonts"), { recursive: true });
const rules = [];
const push = (...lines) => rules.push(lines.join("\n"));

for (const family of FAMILIES) {
	const latin = measure({
		family: { pkg: family.pkg },
		name: `${family.pkg}-latin-${family.weights[0]}-normal.woff2`,
	});
	const fb = fallbackFace(latin);
	push(
		`/* NOTE: Generated by scripts/gen-fonts.mjs - regenerate, do not edit. */`,
		`@font-face {`,
		`\tfont-family: "${family.family} Fallback";`,
		`\tsrc: local("Arial");`,
		`\tsize-adjust: ${fb.sizeAdjust};`,
		`\tascent-override: ${fb.ascent};`,
		`\tdescent-override: ${fb.descent};`,
		`\tline-gap-override: ${fb.lineGap};`,
		`}`,
	);
	for (const weight of family.weights) {
		for (const face of parseFaces(family.pkg, weight)) {
			const name = `${family.pkg}-${face.subset}-${weight}-normal.woff2`;
			copyFileSync(
				join(
					WEB,
					"node_modules",
					"@fontsource",
					family.pkg,
					"files",
					face.file,
				),
				join(WEB, "static", "fonts", name),
			);
			push(
				`@font-face {`,
				`\tfont-family: "${family.family}";`,
				`\tfont-style: normal;`,
				`\tfont-weight: ${weight};`,
				`\tfont-display: swap;`,
				`\tsrc: url("/fonts/${name}") format("woff2");`,
				`\tunicode-range: ${face.range};`,
				`}`,
			);
		}
	}
}

const outPath = join(WEB, "src", "fonts.generated.css");
const config = await prettier.resolveConfig(outPath);
const formatted = await prettier.format(rules.join("\n\n"), {
	...config,
	filepath: outPath,
});
writeFileSync(outPath, formatted);
console.log(`fonts.generated.css written: ${rules.length} rules`);
